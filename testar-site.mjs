// Abre o site da Turma do Brasil no ar, num celular simulado, com o mapa 3D, e confere a coluna de patrocinadores. Só olha: não toca em nenhum botão que conte clique.
import fs from "node:fs";
import { chromium } from "playwright";
const SITE = "https://brasildaturma.online/", OUT = "fotos-site";
fs.mkdirSync(OUT, { recursive: true });
let falhas = 0;
const confere = (n, c) => { console.log(`${c ? "OK  " : "FALHA"} ${n}`); if (!c) falhas++; };
const nav = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-webgl", "--ignore-gpu-blocklist", "--enable-unsafe-swiftshader"] });
const pg = await nav.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const erros = []; pg.on("pageerror", (e) => erros.push(e.message));
await pg.goto(SITE);
await pg.waitForFunction(() => document.getElementById("carregando")?.classList.contains("some"), null, { timeout: 180000 });
await pg.waitForTimeout(4000);
await pg.screenshot({ path: `${OUT}/1-popup.png` });
const popup = await pg.$(".modal-ok"); if (popup) await popup.tap();
await pg.waitForSelector("#patro:not([hidden]) .patro-i", { timeout: 30000 });
await pg.waitForTimeout(5000);
await pg.screenshot({ path: `${OUT}/2-entrada.png` });
confere("mapa desenhado (canvas ocupa a tela)", await pg.$eval("#mapa", (c) => c.width > 300 && c.height > 300));
confere("site saiu do Carregando", await pg.$eval("#carregando", (e) => getComputedStyle(e).display === "none" || e.classList.contains("some")));
confere("4 lugares na coluna", (await pg.$$("#patro .patro-i")).length === 4);
confere("chamada com a frase", (await pg.textContent("#patro .patro-chamada")).includes("Clique em saiba mais"));
confere("coluna não encosta no placar", await pg.evaluate(() => document.querySelector("#patro .patro-col").getBoundingClientRect().bottom <= document.getElementById("placar").getBoundingClientRect().top));
const casas = await pg.evaluate(async () => (await (await fetch(`${window.CONFIG.api}/dados/casas.json`)).json()).casas.length);
console.log("casas no mapa:", casas);
const quem = await pg.evaluate(async () => (await (await fetch(`${window.CONFIG.api}/dados/casas.json`)).json()).topSemana?.[0]?.u);
await pg.fill("#busca-txt", "@" + quem); await pg.press("#busca-txt", "Enter");
await pg.waitForSelector("#cartao:not([hidden])", { timeout: 20000 });
await pg.waitForTimeout(3000);
await pg.screenshot({ path: `${OUT}/3-casa.png` });
confere("casa aberta: coluna e chamada somem", await pg.$eval("#patro", (e) => e.hidden && getComputedStyle(e).display === "none"));
await pg.tap("#cartao-fechar"); await pg.waitForTimeout(1500);
await pg.screenshot({ path: `${OUT}/4-casa-fechada.png` });
confere("fechou a casa: continuam fora", await pg.$eval("#patro", (e) => e.hidden));
await pg.goto(SITE + "patrocinio.html"); await pg.waitForSelector("#form:not([hidden])", { timeout: 20000 }); await pg.waitForTimeout(1500);
await pg.screenshot({ path: `${OUT}/5-venda.png`, fullPage: true });
confere("venda aberta, com o número real de casas", /\d/.test(await pg.textContent("#n-casas")));
confere("sem erro de JavaScript", erros.length === 0); if (erros.length) console.log(erros);
await nav.close();
console.log(falhas ? `${falhas} falha(s)` : "Tudo certo"); process.exit(falhas ? 1 : 0);
